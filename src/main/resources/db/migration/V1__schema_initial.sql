create table canal (
                       id   integer generated by default as identity primary key,
                       name varchar(255) not null
);

create table ue (
                    id   integer generated by default as identity primary key,
                    name varchar(255) not null unique
);

create table person (
                        id         integer generated by default as identity primary key,
                        full_name  varchar(255) not null,
                        promotion  varchar(20)  not null check (promotion in ('MSP1', 'MSP2', 'POLYTECH_OTHER', 'NOT_POLYTECH')),
                        visitor_id uuid         not null unique,
                        created_at timestamp(6) not null
);

create table link (
                      id               integer generated by default as identity primary key,
                      short_code       uuid         not null unique,
                      title            varchar(255) not null,
                      url              varchar(255) not null,
                      publication_date timestamp(6) not null,
                      active           boolean      not null,
                      ue_id            integer,
                      canal_id         integer,
                      constraint fk_link_ue    foreign key (ue_id)    references ue (id),
                      constraint fk_link_canal foreign key (canal_id) references canal (id)
);

create table clic (
                      id        integer generated by default as identity primary key,
                      date_time timestamp(6) not null,
                      link_id   integer      not null,
                      person_id integer,
                      constraint fk_clic_link   foreign key (link_id)   references link (id),
                      constraint fk_clic_person foreign key (person_id) references person (id)
);

create table account (
                         id            integer generated by default as identity primary key,
                         username      varchar(255) not null unique,
                         password_hash varchar(255) not null
);